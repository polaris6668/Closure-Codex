import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import { TOKENS } from '../src/palette.mjs'

const root = fileURLToPath(new URL('../', import.meta.url))
const { name } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))
const css = await readFile(path.join(root, 'src/theme.css'), 'utf8')
const source = (await readFile(path.join(root, 'src/client.js'), 'utf8'))
  .replace("import { TOKENS } from './palette.mjs'", `const TOKENS = ${JSON.stringify(TOKENS)}`)
  .replace("'__CLOSURE_DSH_CSS__'", JSON.stringify(css))
  .replace(/^export /gm, '')
// DSH's client module loader consumes registered CommonJS factories, not raw ESM.
// There are no runtime imports, build dependencies, remote assets or font files.
const bundle = `// Generated by tools/build.mjs; edit src/ instead.\nwindow.__ModuleLoader__.load({\n  id: ${JSON.stringify(name)},\n  factory: () => {\n${source}\nreturn { inject, apply }\n  }\n})\n`
await writeFile(path.join(root, 'lib/client.js'), bundle)
console.log(`Built ${name}: ${Buffer.byteLength(bundle)} bytes, ${Object.keys(TOKENS).length} colour tokens`)
